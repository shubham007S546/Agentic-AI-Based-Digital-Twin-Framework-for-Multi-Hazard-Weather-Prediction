      <h1>Dipole Mode Index  (DMI)  </h1>
	  <p>The DMI  index is an indicator of the east-west temperature gradient across the tropical Indian Ocean, linked to the Indian Ocean Dipole or Zonal Mode. It is calculated as the difference of the WTIO and SETIO indices. Extreme September-October-November rainfall in tropical East Africa has associated with periods of persistently high DMI (Black et al.,<em>Mon. Wea. Rev.</em>, 2003; this paper can be accessed via the AMS Web site <a href="http://ams.allenpress.com/perlserv/?request=get-document&doi=10.1175%2F1520-0493(2003)131%3C0074:AOSOTR%3E2.0.CO%3B2">here</a>). </p>
<p>In the full series case, monthly averages are shown by the plus signs, three month running mean filtered index values are shown by the shaded regions. In the "last two years" case, weekly averages are shown by the plus signs and the monthly average values are shown by the shaded regions.The weekly standard deviation of the index over the period 1991-2020 is indicated on the plot.  </p>
	  <p>This index was defined by Saji et al. (<em>Nature</em>, 1999).</p>
	  <p>The Australian Bureau of Meteorology hosts an <a href="http://www.bom.gov.au/climate/iod">Indian Ocean Dipole page</a> with more information, including forecasts. </p>
	  <h2>Data source</h2>
	  <p>The index is calculated using the <a href="http://www.emc.ncep.noaa.gov/research/cmb/sst_analysis/">Reynolds OIv2 SST analysis</a>, made available by <a href="https://www.esrl.noaa.gov/psd/data/gridded/data.noaa.oisst.v2.html">NOAA/ESRL</a>, and is updated weekly (last update 21-JUN-2026).&nbsp;&nbsp; <a href="../data/dmi.nc">get&nbsp;series&nbsp;(netcdf&nbsp;24kB)&nbsp;&raquo;</a>&nbsp; <a href="../data/dmi_uncertainty.nc">get&nbsp;error&nbsp;(netcdf&nbsp;24kB)&nbsp;&raquo;</a> </p>
	  <h2>Calculation</h2>
	  <p>
The anomaly is calculated relative to a monthly climatological seasonal cycle based on the years 1991-2020. The monthly climatology is linearly interpolated to determine weekly anomalies.Spatial averaging of the gridded analysis was weighted by surface area. 
</p><h2>Uncertainty </h2>
<p>The uncertainty of the index is estimated to be <b>0.1921 degrees C</b> over the period 1982-present, and is based on the uncertainty estimate obtained from the objective interpolation analysis.

